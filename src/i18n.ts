export const STRINGS: Record<Lang, Strings> = { de, en };

export function pickLang(configured: string | undefined, hassLang: string | undefined): Lang {
  if (configured === "de" || configured === "en") return configured;
  return (hassLang ?? "de").toLowerCase().startsWith("de") ? "de" : "en";
}

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
